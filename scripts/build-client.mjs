import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
export const clientEntry = 'client/dist/client.js';

/** Small deterministic module wrapper; React and primitives stay Host externals. */
export async function bundleClient() {
  const state = await readFile(new URL('client/state.mjs', root), 'utf8');
  const adapter = await readFile(new URL('client/adapter.mjs', root), 'utf8');
  const expectedImport = "import { createController, deriveView, filterProjects } from './state.mjs';";
  if (!adapter.startsWith(expectedImport + '\n')) throw new Error('Unexpected settings adapter import; update the explicit client build.');
  const body = `${state}\n${adapter.slice(expectedImport.length + 1)}`.replace(/^export (?=(?:const|class|function|async function)\b)/gm, '');
  if (/^\s*(?:import|export)\s/m.test(body)) throw new Error('Unexpected client dependency; framework copies must never be bundled.');
  return `// Generated by scripts/build-client.mjs from client/state.mjs + client/adapter.mjs.\n// DSH 0.2.0-rc.2 native settings; no bundled React, Vue, or third-party runtime.\nwindow.__ModuleLoader__.load({\n  id: "dsh-personal-sync",\n  factory: (require) => {\n    "use strict";\n${body}\n    return createClientPlugin(require);\n  }\n});\n`;
}

export async function buildClient() {
  const bundle = await bundleClient();
  const target = new URL(clientEntry, root);
  await mkdir(new URL('client/dist/', root), { recursive: true });
  let existing;
  try { existing = await readFile(target, 'utf8'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (existing !== bundle) await writeFile(target, bundle, 'utf8');
  return fileURLToPath(target);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`Built DSH client: ${await buildClient()}`);
}
