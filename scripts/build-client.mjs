import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
export const clientEntry = 'client/dist/client.js';

/** Explicit deterministic module wrappers. This is deliberately NOT a general
 * transpiler or dependency resolver: only these four trusted modules may enter
 * the bundle; React/primitives remain exact Host externals. */
export async function bundleClient() {
  const modules = ['state.mjs', 'bidirectional-state.mjs', 'bidirectional-panel.mjs', 'adapter.mjs'];
  const built = new Set(), bodies = [];
  for (const name of modules) {
    const source = await readFile(new URL(`client/${name}`, root), 'utf8');
    const exports = [...source.matchAll(/^export (?:async )?(?:const|class|function) ([A-Za-z_$][\w$]*)/gm)].map(match => match[1]);
    if (!exports.length || new Set(exports).size !== exports.length) throw new Error('Missing or duplicate explicit client exports');
    const body = source.replace(/^import \{ ([^}]+) \} from '(\.\/[^']+\.mjs)';$/gm, (_line, members, dependency) => {
      if (!built.has(dependency)) throw new Error('Unexpected client dependency or module order');
      const names = members.split(',').map(item => item.trim());
      if (names.some(item => !/^[A-Za-z_$][\w$]*(?: as [A-Za-z_$][\w$]*)?$/.test(item))) throw new Error('Unsupported client import');
      return `const { ${names.map(item => item.replace(' as ', ': ')).join(', ')} } = __clientModules[${JSON.stringify(dependency)}];`;
    }).replace(/^export (?=(?:const|class|function|async function)\b)/gm, '');
    if (/^\s*(?:import|export)\s/m.test(body)) throw new Error('Unexpected client dependency; framework copies must never be bundled.');
    bodies.push(`__clientModules[${JSON.stringify(`./${name}`)}] = (() => {\n${body}\nreturn Object.freeze({${exports.join(', ')}});\n})();`);
    built.add(`./${name}`);
  }
  return `// Generated by scripts/build-client.mjs from the explicit client module whitelist.\n// DSH 0.2.0-rc.2 native settings; no bundled React, Vue, or third-party runtime.\nwindow.__ModuleLoader__.load({\n  id: "dsh-personal-sync",\n  factory: (require) => {\n    "use strict";\nconst __clientModules = Object.create(null);\n${bodies.join('\n')}\n    return __clientModules['./adapter.mjs'].createClientPlugin(require);\n  }\n});\n`;
}

export async function buildClient() {
  const bundle = await bundleClient();
  const target = new URL(clientEntry, root);
  await mkdir(new URL('client/dist/', root), { recursive: true });
  let existing;
  try { existing = await readFile(target, 'utf8'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (existing !== bundle) await writeFile(target, bundle, 'utf8');
  return fileURLToPath(target);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`Built DSH client: ${await buildClient()}`);
}
